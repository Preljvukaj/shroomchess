const dicts = { de, en };

export function t(key: I18nKey, params: Record<string, string> = {}): string {
  let s = dicts[settings.get().lang][key] ?? de[key] ?? key;
  for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, v);
  return s;
}

export function colorName(c: 'w' | 'b'): string {
  return t(c === 'w' ? 'white' : 'black');
}
