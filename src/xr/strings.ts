export function V(key: VRKey, params: Record<string, string | number> = {}): string {
  let s = (settings.get().lang === 'en' ? en : de)[key];
  for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
